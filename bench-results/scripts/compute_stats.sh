#!/bin/bash
# Compute mean/median/min/max for every completed phase under results_compare/
# and write a Markdown STATS.md summary at the root of the staged bench-results dir.

set -u
RESULTS="${1:-<path>/sqisign-fp-bench/results_compare}"
OUT_DIR="${2:-<path>/compact-SQIsign/bench-results/results_compare}"
OUT="$OUT_DIR/STATS.md"

mkdir -p "$OUT_DIR"

# Stats are wall_med seconds (column 6 of SUMMARY_<phase>.tsv), only counting exit==0 rows.
# Header
{
  echo "# Bench stats (wall-clock seconds, valid runs only)"
  echo ""
  echo "Auto-generated by compute_stats.sh after each block. \`n\` is the number of"
  echo "exit=0 (valid) attempts; \`mean\`/\`median\`/\`min\`/\`max\` are over those."
  echo ""
  echo "| impl | level | phase | n | mean (s) | median (s) | min (s) | max (s) |"
  echo "| ---- | ----- | ----- | --: | -------: | ---------: | ------: | ------: |"
} > "$OUT"

stat_for() {
  # echo: mean median min max n  (or "- - - - 0")
  local f=$1
  [ -f "$f" ] || { echo "- - - - 0"; return; }
  awk -F'\t' '
    NR>1 && $3==0 && $6!="" && $6!="?" { v[++n] = $6 + 0; s += $6 }
    END {
      if (n == 0) { print "- - - - 0"; exit }
      for (i = 2; i <= n; i++) { x = v[i]; j = i - 1
        while (j > 0 && v[j] > x) { v[j+1] = v[j]; j-- }
        v[j+1] = x
      }
      mean = s / n
      if (n % 2 == 1) med = v[(n+1)/2]
      else            med = (v[n/2] + v[n/2+1]) / 2
      printf "%.6f %.6f %.6f %.6f %d\n", mean, med, v[1], v[n], n
    }
  ' "$f"
}

for impl in ours klkl25; do
  for lvl in lvl1 lvl3 lvl5; do
    base="$RESULTS/$impl/$lvl/$lvl"
    [ -d "$base" ] || continue
    for p in keypair sign verify; do
      f="$base/SUMMARY_${p}.tsv"
      [ -f "$f" ] || continue
      read mean med mn mx n <<<"$(stat_for "$f")"
      if [ "$n" = "0" ]; then
        printf "| %s | %s | %s | 0 | - | - | - | - |\n" "$impl" "$lvl" "$p" >> "$OUT"
      else
        printf "| %s | %s | %s | %s | %s | %s | %s | %s |\n" \
          "$impl" "$lvl" "$p" "$n" "$mean" "$med" "$mn" "$mx" >> "$OUT"
      fi
    done
  done
done

# Side-by-side comparison section
{
  echo ""
  echo "## Side-by-side (per level, KeyGen / Sign / Verify; wall-clock seconds)"
  echo ""
} >> "$OUT"

for lvl in lvl1 lvl3 lvl5; do
  echo "" >> "$OUT"
  echo "### $lvl" >> "$OUT"
  echo "" >> "$OUT"
  echo "| Implementation | KeyGen mean | KeyGen median | Sign mean | Sign median | Verify mean | Verify median |" >> "$OUT"
  echo "| -------------- | ----------: | ------------: | --------: | ----------: | ----------: | ------------: |" >> "$OUT"
  for impl in klkl25 ours; do
    base="$RESULTS/$impl/$lvl/$lvl"
    if [ ! -d "$base" ]; then continue; fi
    label="KLKL25"; [ "$impl" = "ours" ] && label="Ours"
    read kg_mean kg_med _ _ kg_n  <<<"$(stat_for "$base/SUMMARY_keypair.tsv")"
    read sg_mean sg_med _ _ sg_n  <<<"$(stat_for "$base/SUMMARY_sign.tsv")"
    read vf_mean vf_med _ _ vf_n  <<<"$(stat_for "$base/SUMMARY_verify.tsv")"
    fmt() { if [ "$1" = "-" ]; then echo "—"; else printf "%s" "$1"; fi; }
    printf "| %s | %s (n=%s) | %s | %s (n=%s) | %s | %s (n=%s) | %s |\n" \
      "$label" "$(fmt "$kg_mean")" "$kg_n" "$(fmt "$kg_med")" \
      "$(fmt "$sg_mean")" "$sg_n" "$(fmt "$sg_med")" \
      "$(fmt "$vf_mean")" "$vf_n" "$(fmt "$vf_med")" >> "$OUT"
  done
  # speedup row if both have valid samples
  for impl_set in "klkl25 ours"; do
    base_o="$RESULTS/ours/$lvl/$lvl"; base_k="$RESULTS/klkl25/$lvl/$lvl"
    [ -d "$base_o" ] && [ -d "$base_k" ] || continue
    for phase in keypair sign verify; do :; done
    read _ kg_o _ _ kg_on <<<"$(stat_for "$base_o/SUMMARY_keypair.tsv")"
    read _ kg_k _ _ kg_kn <<<"$(stat_for "$base_k/SUMMARY_keypair.tsv")"
    read _ sg_o _ _ sg_on <<<"$(stat_for "$base_o/SUMMARY_sign.tsv")"
    read _ sg_k _ _ sg_kn <<<"$(stat_for "$base_k/SUMMARY_sign.tsv")"
    read _ vf_o _ _ vf_on <<<"$(stat_for "$base_o/SUMMARY_verify.tsv")"
    read _ vf_k _ _ vf_kn <<<"$(stat_for "$base_k/SUMMARY_verify.tsv")"
    su() {
      local o=$1 k=$2
      [ "$o" = "-" ] || [ "$k" = "-" ] && { echo "—"; return; }
      awk -v o="$o" -v k="$k" 'BEGIN { if (o > 0) printf "%.2fx", k / o; else print "—" }'
    }
    printf "| **Ours speedup (median)** | %s | | %s | | %s | |\n" \
      "$(su "$kg_o" "$kg_k")" "$(su "$sg_o" "$sg_k")" "$(su "$vf_o" "$vf_k")" >> "$OUT"
    break
  done
done
